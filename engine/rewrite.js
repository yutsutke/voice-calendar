// engine/rewrite.js — 長文を「読める文章」に整える（v80・ゆう要求）
//
// 背景（ゆう要求 2026-08-13）: 「**長文になると、文章が不正確になりがち**、AIボタンで文章をリライト
// する機能も加えたい」。長く話すほど音声認識は崩れる（同音異義・句読点なし・言い淀みが混じる）。
// v58 で「タイトルは簡素・全文はメモ」にしたので、**崩れた全文はメモ欄に居る**＝直す対象はそこ。
//
// なぜ engine に置くか: 指示文も検証も**宿主（DOM）も特定の AI も知らない純関数**にする。
//   ai.js は「文字列を投げて文字列を受ける」だけ（契約を知らない）＝この層を差し替えれば用途が変わる。
//   ライフログ `plans` へ移す時もそのまま動く（SPEC §6 中立スキーマ）。
//
// 🚫 **AI は創作しない**（SPEC §7）＝ここでの「整える」は次の4つだけに縛る:
//    ①文脈から明らかな変換ミスの訂正 ②句読点・改行 ③言い淀みの削除 ④言い直しの重複整理
//    足す・要約する・文体を変える・順番を変えるのは**させない**（指示文と検証の両方で縛る）。
//
// 🔑 **AI の出力を信用しない**（v39 の検証ゲートと同じ姿勢）。ただし相手が散文なので、
//    機械が確かめられるのは「**壊れ方**」だけ＝空・前置き付き・極端な伸縮。**中身の正しさは人が見る**。
//    だから宿主側は必ず ①黙って書き換えない（来歴に痕跡） ②1タップで戻せる ③自動保存しない、を守る。
(function (global) {
  'use strict';

  // これ未満は出さない。短い発話は認識がよく当たる（v22 の観察）＝整える価値がなく、
  // ボタンだけが増える。40 は v58 が「区切りが無くても長い」と判断する境目と同じ数字。
  const MIN_CHARS = 40;

  // 🆕 v84: **推敲画面を挟む長さ**（ゆう要求「長い文章の時にはそれに対応した UI を一つ挟む」）。
  // MIN_CHARS(40) より高くしてある＝40 は「整えるボタンを**そっと出す**」境目（受け身の提案）だが、
  // こちらは**画面を挟んで手を止めさせる**（能動的な割り込み）。割り込みの敷居は提案より高いのが筋。
  // 80字 ≒ 一段落。「明日15時に歯医者」のような1件の予定は絶対に届かない＝普段の一本道は無傷。
  const REVIEW_MIN_CHARS = 80;

  // 🆕 v94: **自動で要約が走る境目**（ゆう要求「ある程度しゃべると、自動に要約がはしる設定も欲しい」）。
  // 数え方は「本文の総字数」ではなく **前回 AI を当ててから声で足した分**（下の shouldAutoSummarize）。
  // 🚨 総字数で数えると**要約の要約**が延々と走る（400字→要約100字→また閾値を超えれば走る…）＝
  //    要らない情報の欠落が積み上がる。「足した分」で数えれば、走るのは**新しく話した分が溜まった時だけ**。
  // 100字 ≒ 話し言葉で数十秒ぶん。当初 300字（1分ぶん）で出したが、ゆうが実機で「300字はおおいね。
  // １００文字ぐらいに」（2026-08-30）＝実測の体感で下げた。下書きを開いた最初の発話は数えない
  //（openReview で 0 から数え直す）ので、これは**続きとして話した分**の境目。
  const AUTO_SUMMARY_CHARS = 100;

  // 🆕 v84: AI に文章を作り直させる操作は2つ（ゆう要求「AIで要約、文章を整える、などのボタン」）。
  // **指示文と受け入れ幅を1つの表にまとめる**＝新しい操作が増えても、書く場所が1箇所で済む
  // （プロンプトだけ別、判定だけ別、に散らすと v74 の形になる）。
  //   min/max = 出来上がりの長さの比。ここを外れたら**当てずに理由を出す**（v16）。
  const MODES = {
    // 整える: 長さはほぼ変わらないはず。言い淀みを消すと2〜3割縮み、句読点を足すと少し伸びる。
    tidy: {
      label: '文章を整える',
      done: '整えました',   // ラベルは辞書形＝そのまま「ました」を付けると壊れる（実測で気づいた）
      min: 0.5,
      max: 1.5,
      tooShort: (b, t) => `短くなりすぎました（${b}字→${t}字）＝要約された可能性があるので当てません`,
      tooLong: (b, t) => `長くなりすぎました（${b}字→${t}字）＝書き足された可能性があるので当てません`,
      prompt: () => [
        'あなたは日本語の音声認識の結果を「読める文章」に直す校正者です。',
        '',
        '【必ず守ること】',
        '- 内容を足さない・減らさない。要約しない。見出しや感想を付けない。',
        '- 事実（人名・地名・数字・日付・時刻・金額）を変えない。読みが同じでも、確信が無ければそのままにする。',
        '- 文体を変えない。話し言葉は話し言葉のまま。敬語に直さない。',
        '- 文の順番を入れ替えない。',
        '',
        '【直してよいこと（これだけ）】',
        '1. 音声認識の変換ミス（同音異義語）を、前後の文脈から明らかな場合だけ直す',
        '2. 句読点（、。）を入れて文を区切る。長ければ改行を入れる',
        '3. 言い淀み（えー、あの、えっと、まあ）を消す',
        '4. 同じことを言い直している箇所は、後の言い方を残して重複を消す',
        '',
        '【出力】',
        '直した本文だけを返す。前置き・説明・引用記号（```）を付けない。',
        '直すところが無ければ、受け取った本文をそのまま返す。',
      ].join('\n'),
    },
    // 要約: **短くなるのが正しい**＝「短すぎる」で落とす下限はごく低く、逆に**伸びたら異常**。
    // 🚨 要約は本来「減らす」操作＝SPEC §7「創作しない」といちばん緊張する。だから
    //    (a) 人が押した時だけ動く (b) 元の文章に1タップで戻せる (c) 指示文で創作を明確に禁じる。
    summarize: {
      label: '要約する',
      done: '要約しました',
      min: 0.05,
      max: 0.9,
      tooShort: (b, t) => `短くなりすぎました（${b}字→${t}字）＝要点まで落ちている可能性があるので当てません`,
      tooLong: (b, t) => `要約なのに長くなりました（${b}字→${t}字）＝書き足された可能性があるので当てません`,
      prompt: () => [
        'あなたは日本語の話し言葉を要約する編集者です。',
        '',
        '【必ず守ること】',
        '- 書かれていないことを足さない。推測で補わない。',
        '- 事実（人名・地名・数字・日付・時刻・金額）を変えない。',
        '- 元に無い結論・評価・助言・感想を書かない。',
        '- 元の言い方をできるだけそのまま使う（言い換えて短くしない）。',
        '',
        '【やること】',
        '- 要点だけを残して短くする。項目が複数あれば箇条書きにしてよい。',
        '- 予定や約束（日時・場所・相手）が含まれていれば、それは必ず残す。',
        '',
        '【出力】',
        '要約した本文だけを返す。前置き・説明・引用記号（```）を付けない。',
      ].join('\n'),
    },
  };

  // v80 の呼び出し（引数なし）は「整える」のまま動く＝既存の体験を変えない。
  const modeOf = (m) => MODES[m] || MODES.tidy;
  function buildPrompt(mode) { return modeOf(mode).prompt(); }

  // 後方互換（v80 が公開していた数字。中身は tidy の幅そのもの＝二重に持たない）
  const MIN_RATIO = MODES.tidy.min;
  const MAX_RATIO = MODES.tidy.max;

  // AI は指示しても前置きや ``` を付けてくることがある＝**捨てずに剥がす**（v16: 黙って捨てない／
  // ここで剥がさないと本文の頭に「以下が整えた文章です：」が混ざったまま欄へ入る）。
  function clean(raw) {
    let t = String(raw == null ? '' : raw).replace(/\r\n/g, '\n').trim();
    // ```／```text で囲まれている場合は中身だけ取る
    const fence = t.match(/^```[a-zA-Z]*\n([\s\S]*?)\n?```$/);
    if (fence) t = fence[1].trim();
    // 1行目が前置きだけ（本文が続く）なら落とす。**本文らしい行は落とさない**ため、
    // 「〜です：」「〜します：」で終わる短い行だけを対象にする。
    const lines = t.split('\n');
    if (lines.length > 1 && /^.{0,30}(です|ます|した)[:：]$/.test(lines[0].trim())) {
      t = lines.slice(1).join('\n').trim();
    }
    return t;
  }

  // before → after が受け入れられるか。落とす時は**必ず理由を返す**（v16）。
  // 返り値: { ok, text, problem }（problem は ok=false の時だけ・そのまま画面に出せる日本語）
  // v84: mode で受け入れ幅と文言が変わる（既定は tidy＝v80 の挙動そのまま）。
  function check(before, after, mode) {
    const m = modeOf(mode);
    const b = String(before == null ? '' : before).trim();
    const t = clean(after);
    if (!t) return { ok: false, text: '', problem: 'AI が空の文章を返しました' };
    if (!b) return { ok: false, text: '', problem: '元の文章がありません' };
    if (t === b) return { ok: false, text: t, problem: '直すところはありませんでした', same: true };
    const ratio = t.length / b.length;
    if (ratio < m.min) return { ok: false, text: t, problem: m.tooShort(b.length, t.length) };
    if (ratio > m.max) return { ok: false, text: t, problem: m.tooLong(b.length, t.length) };
    return { ok: true, text: t };
  }

  // 「整えるボタンを出すか」＝長い時だけ。判定を宿主に書かない（宿主が数字を持つと二重管理になる）。
  function isLongEnough(text) {
    return String(text == null ? '' : text).trim().length >= MIN_CHARS;
  }

  // 🆕 v84: 「この発話は推敲画面を挟むか」＝**長さだけ**で決める（数字は engine が持つ）。
  // 🚫 中身では判断しない（意味を判定しない＝v27/v28 の線）。長さは機械が確実に測れる唯一の手がかり。
  function needsReview(text) {
    return String(text == null ? '' : text).trim().length >= REVIEW_MIN_CHARS;
  }

  // 🆕 v94: 推敲画面で**続きを声で足す**時の足し方（ゆう要求「編集した後にまた、その文章の続きを
  // 音声で入力できるようにしてほしい」）。区切り方を宿主に書かない＝ここが唯一の決定。
  // 🔑 **改行で区切る**（句点を足さない）＝ 足すのは「話した通りの文字」だけ＝**創作しない**（SPEC §7）。
  //   要約した後に続きを足す使い方（ゆうの流れ）では、要約と生の続きが**見て分かれている**方が直しやすい。
  // 空はそのまま返す（空を足して余計な改行だけ増やさない）。
  function appendSpoken(base, add) {
    const b = String(base == null ? '' : base).replace(/\s+$/, '');
    const a = String(add == null ? '' : add).trim();
    if (!a) return b;
    if (!b) return a;
    return b + '\n' + a;
  }

  // 🆕 v94: 自動要約を走らせるか。**前回 AI を当ててから声で足した字数**だけで決める。
  // 🚫 中身では判断しない（意味を判定しない＝v27/v28 の線）。
  // 🚫 手で打った分は数えない（宿主側の責任）＝キーを打つたびに AI が走る画面を作らない。
  function shouldAutoSummarize(addedSinceAi) {
    const n = Number(addedSinceAi);
    return Number.isFinite(n) && n >= AUTO_SUMMARY_CHARS;
  }

  const api = {
    MIN_CHARS, MIN_RATIO, MAX_RATIO, REVIEW_MIN_CHARS, AUTO_SUMMARY_CHARS, MODES,
    buildPrompt, clean, check, isLongEnough, needsReview, appendSpoken, shouldAutoSummarize,
  };
  if (typeof module !== 'undefined' && module.exports) module.exports = api;
  else global.VCRewrite = api;
})(typeof window !== 'undefined' ? window : globalThis);
